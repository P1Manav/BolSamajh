"""Dump worst 5 clips per model from benchmark_data/per_clip_results.jsonl into BENCHMARK_RESULTS.md.

Adheres to Tier 1 Guidelines:
- Reads strictly from benchmark_data/per_clip_results.jsonl.
- Zero invented clips, quotes, or numbers.
- Computes top 5 highest-WER clips for each model.
- Inserts or replaces Section 3 in benchmark_data/BENCHMARK_RESULTS.md.
"""

import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ROOT_DIR = Path(__file__).resolve().parent.parent
PER_CLIP_JSONL = ROOT_DIR / "benchmark_data" / "per_clip_results.jsonl"
BENCHMARK_MD = ROOT_DIR / "benchmark_data" / "BENCHMARK_RESULTS.md"


def load_per_clip_results(path: Path) -> Dict[str, List[Dict[str, Any]]]:
    if not path.exists():
        raise FileNotFoundError(f"Per-clip results file not found: {path}")

    records_by_model: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            records_by_model[rec["model"]].append(rec)
    return records_by_model


def get_top_worst_clips(records: List[Dict[str, Any]], n: int = 5) -> List[Dict[str, Any]]:
    # Sort primarily by WER descending, secondarily by latency descending
    return sorted(
        records, key=lambda r: (r.get("wer", 0.0), r.get("latency_ms", 0.0)), reverse=True
    )[:n]


def generate_worst_clips_markdown(records_by_model: Dict[str, List[Dict[str, Any]]]) -> str:
    lines = [
        "## 3. Top 5 Worst Clips Per Model (Empirically Measured)",
        "",
        "> Automatically generated by `scripts/dump_worst_clips.py` from `benchmark_data/per_clip_results.jsonl`.",
        "> Displays the 5 highest-WER clips for each evaluated model with exact references and raw hypotheses.",
        "",
    ]

    for model_name, records in records_by_model.items():
        worst = get_top_worst_clips(records, n=5)
        lines.append(f"### Model: `{model_name}` (Total Evaluated Clips: {len(records)})")
        lines.append("")

        for idx, clip in enumerate(worst, 1):
            clip_id = clip.get("clip_id", "unknown")
            wer_pct = round(clip.get("wer", 0.0) * 100, 2)
            dur = round(clip.get("audio_duration", 0.0), 2)
            lat = round(clip.get("latency_ms", 0.0), 1)
            device = clip.get("device", "unknown")
            ref = clip.get("reference", "").strip()
            hyp = clip.get("raw_hypothesis", "").strip()
            canon_ref = clip.get("canonical_ref", clip.get("normalized_ref", "")).strip()
            canon_hyp = clip.get("canonical_hyp", clip.get("normalized_hyp", "")).strip()

            lines.append(f"#### Clip {idx}: `{clip_id}` — WER: **{wer_pct}%**")
            lines.append(
                f"- **Audio Duration:** {dur} s | **Device:** `{device}` | **Latency:** {lat} ms"
            )
            lines.append(f"- **Reference:** `{ref}`")
            lines.append(f"- **Raw Hypothesis:** `{hyp}`")
            lines.append(f"- **Normalized Reference:** `{canon_ref}`")
            lines.append(f"- **Normalized Hypothesis:** `{canon_hyp}`")
            lines.append("")

    return "\n".join(lines)


def update_benchmark_results_markdown():
    if not BENCHMARK_MD.exists():
        raise FileNotFoundError(f"Benchmark results markdown not found: {BENCHMARK_MD}")

    records_by_model = load_per_clip_results(PER_CLIP_JSONL)
    section_md = generate_worst_clips_markdown(records_by_model)

    content = BENCHMARK_MD.read_text(encoding="utf-8")

    marker_start = "<!-- WORST_CLIPS_START -->"
    marker_end = "<!-- WORST_CLIPS_END -->"

    if marker_start in content and marker_end in content:
        pattern = f"{marker_start}.*?{marker_end}"
        replacement = f"{marker_start}\n\n{section_md}\n\n{marker_end}"
        new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    else:
        # Replace existing Section 3 if present
        sec3_match = re.search(
            r"## 3\. Top 5 Worst Clips.*?(?=## 4\.|\Z)", content, flags=re.DOTALL
        )
        if sec3_match:
            replacement = f"{marker_start}\n\n{section_md}\n\n{marker_end}\n\n"
            new_content = content[: sec3_match.start()] + replacement + content[sec3_match.end() :]
        else:
            raise RuntimeError("Could not find Section 3 or marker tags in BENCHMARK_RESULTS.md")

    BENCHMARK_MD.write_text(new_content, encoding="utf-8")
    print(f"[OK] Successfully updated Section 3 in {BENCHMARK_MD} with real clips.")


if __name__ == "__main__":
    update_benchmark_results_markdown()
